const { PGlite } = require('@electric-sql/pglite');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  const sql = name => readFileSync(join(__dirname, '../supabase', name), 'utf8');
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key, raw_user_meta_data jsonb);
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
    grant usage on schema public, auth to anon, authenticated;`);
  await db.exec(sql('schema.sql').replace('create extension if not exists "pgcrypto";', ''));
  // simula o banco antigo que ficou sem a função de criar perfil
  await db.exec('drop trigger on_auth_user_created on auth.users; drop function public.handle_new_user();');
  await db.exec(sql('security-hardening.sql'));
  await db.exec(sql('rate-limits.sql'));
  await db.exec(sql('budget-workflow.sql'));
  await db.exec(sql('budget-workflow.sql'));
  const ids = [1,2,3].map(n => `00000000-0000-0000-0000-00000000000${n}`);
  for (let i=0;i<3;i++) await db.query('insert into auth.users values ($1, $2)', [ids[i], JSON.stringify({ role: i === 2 ? 'profissional' : 'cliente', services: [] })]);
  assert.equal((await db.query('select count(*)::int as total from public.profiles')).rows[0].total, 3);
  const act = async n => db.exec(`reset role; set test.uid = '${n ? ids[n-1] : ''}'; set role ${n ? 'authenticated' : 'anon'};`);
  const denied = async (statement, code='42501') => assert.rejects(db.exec(statement), e => { assert.equal(e.code, code); return true; });
  await act(1);
  assert.equal((await db.query('select * from public.profiles')).rows.length, 1);
  await denied("update public.profiles set role='profissional'");
  await denied(`insert into public.profiles(id, role) values ('${ids[0]}', 'profissional')`);
  await db.exec("update public.profiles set city='São Paulo'");
  await denied("update public.profiles set whatsapp='invalid'", '23514');
  await denied(`insert into public.services(provider_id,title,category,provider,price,description,uf,city,neighborhood) values ('${ids[0]}','Teste','Teste','Teste','10','Teste','SP','São Paulo','Centro')`);
  await act(3);
  const service = await db.query(`insert into public.services(provider_id,title,category,provider,price,description,uf,city,neighborhood)
    values ($1,'Serviço','Teste','Profissional','10','Descrição','SP','São Paulo','Centro') returning id`, [ids[2]]);
  const serviceId = service.rows[0].id;
  await act(1);
  await db.query(`insert into public.budgets(user_id,professional_id,service_id,client,service,value,details,status)
    values ($1,$2,$3,'Cliente','Serviço','10','Consertar torneira','solicitado')`, [ids[0], ids[2], serviceId]);
  await denied(`insert into public.budgets(user_id,client,service,value,status) values ('${ids[0]}','Cliente','Serviço','10','realizado')`);
  await denied(`insert into public.budgets(user_id,client,service,value) values ('${ids[1]}','Cliente','Serviço','10')`);
  await denied('select whatsapp from public.budgets');
  await denied('delete from private.write_rate_limits');
  await act(2);
  assert.equal((await db.query('select id from public.budgets')).rows.length, 0);
  await act(3);
  assert.equal((await db.query('select id from public.budgets')).rows.length, 1);
  await denied("update public.budgets set status='realizado'");
  await db.exec("update public.budgets set status='cotado', quote_amount=125.50, quote_message='Inclui materiais'");
  await act(1);
  await db.exec("update public.budgets set status='aceito'");
  await denied("update public.budgets set status='em_andamento'");
  await act(3);
  await db.exec("update public.budgets set status='em_andamento'");
  await db.exec("update public.budgets set status='realizado'");
  await act(1);
  assert.equal((await db.query('select id from public.completed_jobs')).rows.length, 1);
  await db.exec('update public.completed_jobs set rating=5');
  await denied("update public.budgets set value='999'");
  await denied(`update public.budgets set user_id='${ids[2]}'`);
  await act(3);
  await db.exec(`insert into public.services(provider_id,title,category,provider,price,description,uf,city,neighborhood) values ('${ids[2]}','Teste','Teste','Teste','10','Teste','SP','São Paulo','Centro')`);
  await denied('update public.services set rating=5');
  await act(0);
  await denied('select * from public.profiles');
  await denied('select id from public.budgets');
  assert.ok((await db.query('select title from public.services')).rows.length);
  await db.close();
  console.log('PASS: rls, acesso entre contas, permissões por coluna, mass assignment, validação e reaplicação.');
})().catch(error => { console.error(error); process.exitCode=1; });
